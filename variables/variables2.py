#Operadores de pertenencia e identidad, in y not in 
nombrar = 5
bienvenida = f"Hola {nombrar} ¿como estas?" 

print("ola" in bienvenida) #aca le estoy diciendo que si ola esta en bienvenida utilizando in y es true por que si esta
print("ola" not in bienvenida) #aca le estoy diciendo que si ola no esta en bienvenida utilizando not in y es falso por que no esta

